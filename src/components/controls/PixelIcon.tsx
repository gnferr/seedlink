  spring: ["...#.#...", "..#####..", ".###.###.", "..##o##..", ".###.###.", "..#####..", "...#.#...", ".........", "........."],
  summer: ["....#....", ".#.....#.", "...###...", "..#####..", "#.#####.#", "..#####..", "...###...", ".#.....#.", "....#...."],
  autumn: [".....####", "....#####", "...######", "..######.", ".#####...", ".###.....", "#........", ".........", "........."],
